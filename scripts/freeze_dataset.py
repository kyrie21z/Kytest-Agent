"""一次性脚本：下载 HumanEval+ 并冻结 30 个固定实例到仓库。

为什么要把数据固化进仓库而不是运行评测时下载：

1. **可复现**：实例 ID 与内容都不随上游变动。评测协议一旦冻结，"根据结果换样本"
   这条路就被物理堵死。
2. **离线**：评测不需要网络，也不给 Agent 留下"上网找答案"的通道。
3. **体积可控**：完整数据集 164 题约 900KB，其中参考答案与**全部**官方测试都要保留
   ——官方测试是我们最强的 baseline（"我们生成的测试达到官方测试杀伤率的 X%"），
   只取 30 题也无法预估是哪 30 题，所以整份下载后抽取。

选择规则是确定性的：按 task_id 的数值排序后等距抽样。不用随机数，
这样任何人重跑这个脚本都得到同一份子集。

用法：
    python scripts/freeze_dataset.py            # 默认 30 例
    python scripts/freeze_dataset.py --count 40
"""
from __future__ import annotations

import argparse
import gzip
import json
import sys
import urllib.request
from pathlib import Path
from typing import Any, Dict, List

SOURCE_URL = "https://raw.githubusercontent.com/evalplus/humanevalplus_release/main/HumanEvalPlus.jsonl.gz"
SOURCE_NAME = "HumanEval+ (EvalPlus)"
SOURCE_CITATION = (
    "Liu et al. Is Your Code Generated by ChatGPT Really Correct? "
    "Rigorous Evaluation of Large Language Models for Code Generation. NeurIPS 2023."
)
SOURCE_LICENSE = "Apache-2.0 (EvalPlus) / MIT (HumanEval)"

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / "benchmarks" / "humaneval_plus_30.jsonl"
META = REPO_ROOT / "benchmarks" / "DATASET.md"


def download(url: str) -> List[Dict[str, Any]]:
    print(f"下载 {url}")
    with urllib.request.urlopen(url, timeout=120) as response:
        raw = response.read()
    text = gzip.decompress(raw).decode("utf-8")
    records = [json.loads(line) for line in text.splitlines() if line.strip()]
    print(f"  解压后 {len(records)} 条记录")
    return records


def task_number(task_id: str) -> int:
    """`HumanEval/123` → 123，用于确定性排序。"""
    return int(str(task_id).rsplit("/", 1)[-1])


def pick(records: List[Dict[str, Any]], count: int) -> List[Dict[str, Any]]:
    """等距抽样，结果与顺序完全确定，不依赖随机数。"""
    ordered = sorted(records, key=lambda item: task_number(item["task_id"]))
    if count >= len(ordered):
        return ordered
    step = len(ordered) / count
    picked = [ordered[int(index * step)] for index in range(count)]
    # 等距抽样可能取到重复项（当 count 与 len 不互质时不会，但保险起见去重）
    unique: List[Dict[str, Any]] = []
    seen = set()
    for item in picked:
        if item["task_id"] not in seen:
            seen.add(item["task_id"])
            unique.append(item)
    return unique


def normalize(record: Dict[str, Any]) -> Dict[str, Any]:
    """规范成我们自己的实例格式。

    `solution` 保留原样（它是被测对象），`official_tests` 保留原样（它是 baseline 的
    测量仪器）。任何裁剪都会破坏这两者的用途。
    """
    return {
        "instance_id": record["task_id"],
        "prompt": record["prompt"],
        "solution": record["canonical_solution"],
        "entry_point": record["entry_point"],
        "official_tests": record["test"],
        "contract": record.get("contract", ""),
    }


def build_solution_file(instance: Dict[str, Any]) -> str:
    """被测文件的完整内容：函数签名 + 参考实现。

    直接写成可导入的模块，所以评测时工作区里只有一个 .py 文件，
    Agent 与评测器面对的是同一份事实。
    """
    prompt = instance["prompt"].rstrip("\n")
    solution = instance["solution"]
    if solution and not solution.startswith("\n"):
        solution = "\n" + solution
    if solution and not solution.endswith("\n"):
        solution += "\n"
    return prompt + solution + "\n"


def build_official_test_file(instance: Dict[str, Any]) -> str:
    """把官方测试包成独立的 pytest 文件。

    官方 `test` 字段里定义了 `check(candidate)`；我们额外生成一个 pytest 入口，
    让"官方测试"也能用与 Agent 生成的测试完全相同的方式被执行与测量。
    这是 baseline 可比的前提。
    """
    entry = instance["entry_point"]
    return (
        f"# 官方测试（{SOURCE_NAME}），仅用于评测 baseline，不进入 Agent 工作区。\n"
        f"import pytest\n\n"
        f"from solution import {entry}\n\n\n"
        f"{instance['official_tests']}\n\n\n"
        f"def test_official():\n"
        f"    check({entry})\n"
    )


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="下载并冻结 HumanEval+ 子集")
    parser.add_argument("--count", type=int, default=30, help="子集大小，默认 30")
    parser.add_argument("--source", default=SOURCE_URL, help="数据源 URL")
    parser.add_argument("--output", default=None,
                        help="输出路径，默认 benchmarks/humaneval_plus_30.jsonl。"
                             "写别的文件时必须同时给 --no-meta 或 --meta，避免覆盖评测集说明")
    parser.add_argument("--no-meta", action="store_true",
                        help="不重写 DATASET.md（非评测集用途时必须加，防止覆盖冻结说明）")
    parser.add_argument("--meta", default=None, help="说明文件的输出路径（与 --no-meta 互斥）")
    args = parser.parse_args(argv)
    if args.no_meta and args.meta:
        parser.error("--no-meta 与 --meta 互斥")

    output = Path(args.output) if args.output else OUTPUT

    records = download(args.source)
    selected = [normalize(record) for record in pick(records, args.count)]
    if len(selected) != args.count:
        print(f"错误：只取到 {len(selected)} 条，期望 {args.count}", file=sys.stderr)
        return 1

    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8") as handle:
        for instance in selected:
            handle.write(json.dumps(instance, ensure_ascii=False) + "\n")
    print(f"已写出 {len(selected)} 个实例 → {output}")

    if args.no_meta:
        return 0
    meta = Path(args.meta) if args.meta else META

    meta.write_text(
        "\n".join(
            [
                "# 评测数据集",
                "",
                f"**来源**：{SOURCE_NAME}",
                f"**URL**：{SOURCE_URL}",
                f"**引用**：{SOURCE_CITATION}",
                f"**许可**：{SOURCE_LICENSE}",
                "",
                f"`humaneval_plus_30.jsonl` 是上述数据集的固定子集，共 {len(selected)} 个实例，",
                "由 `scripts/freeze_dataset.py` 生成。选择规则是按 `task_id` 数值排序后**等距抽样**，",
                "不使用随机数——任何人重跑该脚本都会得到同一份子集。",
                "",
                "## 为什么固化进仓库",
                "",
                "1. **可复现**：实例 ID 与内容不随上游变动。协议冻结后，\"根据结果换样本\"这条路被物理堵死。",
                "2. **离线**：评测不需要网络，也不给 Agent 留下上网找答案的通道。",
                "3. **baseline 可比**：官方测试随实例一起保存，它是评测里最强的对照——",
                "   \"我们生成的测试达到官方测试杀伤率的 X%\"。",
                "",
                "## 实例格式",
                "",
                "每行一个 JSON 对象：",
                "",
                "```json",
                "{",
                '  "instance_id": "HumanEval/0",',
                '  "prompt": "函数签名与 docstring（Agent 能看到的部分）",',
                '  "solution": "参考实现（拼在 prompt 之后构成 solution.py）",',
                '  "entry_point": "被测函数名",',
                '  "official_tests": "官方 check(candidate) 测试体",',
                '  "contract": "输入约束说明"',
                "}",
                "",
                "## 子集实例列表",
                "",
                "| # | instance_id | entry_point |",
                "|---:|---|---|",
            ]
            + [
                f"| {index + 1} | `{item['instance_id']}` | `{item['entry_point']}` |"
                for index, item in enumerate(selected)
            ]
            + [""]
        ),
        encoding="utf-8",
    )
    print(f"已写出数据集说明 → {meta}")

    for index, item in enumerate(selected, 1):
        print(f"  {index:>2}. {item['instance_id']:<16} {item['entry_point']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
